/** Статусы План-Факта: одна формула на всю систему.
 *
 *  Шкала — из макета «IT-HONA План-Факт» (решение заказчика 02.08.2026,
 *  выбрано вместо таблицы ТЗ п. 8, с которой макет расходился):
 *
 *    |отклонение| ≤ норма……………… «В норме»
 *    в свою пользу > «проверить»… «Проверить план» (подозрительно хорошо)
 *    в свою пользу ……………………… «Экономия» (расход) / «Выше плана» (доход)
 *    против плана > «критично»…… «Критично»
 *    против плана …………………………… «Внимание»
 *    факта нет ………………………………… «Нет данных»
 *
 *  «В свою пользу» зависит от направления статьи: для дохода хорошо больше
 *  плана, для расхода — меньше. Поэтому формула принимает dir, а не знак.
 *
 *  Пороги настраиваемые (решение заказчика 02.08.2026): хранятся в settings
 *  (pf_norm / pf_warn / pf_check, проценты), по умолчанию — значения макета.
 *  Файл зеркалится на фронтенд в src/lib/badges.ts — правьте оба.
 */

export interface PfThresholds {
  /** ±норма: до этого отклонение считается «В норме» (по умолчанию 2%). */
  norm: number;
  /** Против плана больше этого — «Критично», до — «Внимание» (10%). */
  warn: number;
  /** В свою пользу больше этого — «Проверить план» (25%). */
  check: number;
}

export const PF_DEFAULTS: PfThresholds = { norm: 2, warn: 10, check: 25 };

export type PfDir = 'income' | 'expense';

/** Подпись статуса строки план-факта. fact === null — факт не проведён. */
export function pfStatusLabel(
  plan: number,
  fact: number | null,
  dir: PfDir,
  th: PfThresholds = PF_DEFAULTS,
): string {
  if (fact === null) return 'Нет данных';
  if (!plan) return 'План не указан';
  const dev = fact - plan;
  // Знаменатель по модулю: у строки результата план бывает отрицательным,
  // и деление на него перевернуло бы знак отклонения.
  const pct = Math.abs(dev / plan) * 100;
  if (pct <= th.norm) return 'В норме';
  const good = dir === 'income' ? dev > 0 : dev < 0;
  if (good) {
    if (pct > th.check) return 'Проверить план';
    return dir === 'income' ? 'Выше плана' : 'Экономия';
  }
  return pct > th.warn ? 'Критично' : 'Внимание';
}

/** Порядок порогов: норма меньше обоих старших. Возвращает текст ошибки. */
export function pfValidate(th: PfThresholds): string | null {
  for (const [k, v] of Object.entries(th)) {
    if (!Number.isFinite(v) || v < 0 || v > 100) return `Порог «${k}» — число от 0 до 100`;
  }
  if (th.warn <= th.norm) return 'Порог «Критично» должен быть больше нормы';
  if (th.check <= th.norm) return 'Порог «Проверить план» должен быть больше нормы';
  return null;
}
