/** Валюта учёта.
 *
 *  История развилки. Дизайн-пакет закрывал её решением 02 — «одна валюта,
 *  без пересчёта». 06.08.2026 заказчик решение отменил: «валюта — все валюты
 *  мира». Поэтому API снова принимает валюту операции, а справочник — весь
 *  ISO 4217 (server/src/iso4217.ts), а не пять валют закупок.
 *
 *  Валюта УЧЁТА при этом осталась одна — сомони. Каждая операция хранит и
 *  сумму в своей валюте (amount_dirams + currency_code + rate), и сумму в
 *  сомони (amount_tjs_dirams). Отчёты, план-факт и остатки складывают только
 *  сомони: складывать доллары с рублями нельзя, а пересчитывать отчёт на лету
 *  по сегодняшнему курсу — значит менять прошлое при каждом открытии.
 */

import { isIsoCurrency } from './iso4217';

export const BASE_CURRENCY = 'TJS';

/** Мультивалютность включена; флаг оставлен как единая точка выключения. */
export const SINGLE_CURRENCY = false;

/** Валюта запроса приемлема? Пустое значение = валюта по умолчанию. */
export function currencyAllowed(code: string | null | undefined): boolean {
  if (!code) return true;
  if (SINGLE_CURRENCY) return code === BASE_CURRENCY;
  return isIsoCurrency(code);
}

/** Текст ошибки 422 для отклонённой валюты.
 *  Подменять чужую валюту на сомони молча нельзя: сумма при этом остаётся
 *  прежней цифрой, и в отчёт попадает 1000 сомони вместо 1000 долларов. */
export const CURRENCY_DISABLED_MESSAGE = SINGLE_CURRENCY
  ? 'Учёт ведётся в сомони (TJS) — операции в других валютах отключены'
  : 'Неизвестный код валюты — нужен код ISO 4217, например USD или CNY';
