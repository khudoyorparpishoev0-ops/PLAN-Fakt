/** Понятная ошибка входа для регресс-проверок.
 *
 *  Ловушка, на которую наступили при первой проверке боевого сервера
 *  07.08.2026: проверки входят под паролями из `SEED_PASSWORD_*`, а система
 *  требует сменить временный пароль при первом входе. Значит на любой живой
 *  установке эти пароли устаревают в тот же день — и все пять проверок
 *  отвечают голым «401 invalid_credentials», по которому непонятно, что
 *  сломалось: сервер, проверка или учётная запись.
 *
 *  Здесь единственное, что нужно: назвать причину и следующий шаг.
 */

export function loginFailed(email: string, status: number, body: string): never {
  if (status === 401) {
    throw new Error(
      [
        `Вход под ${email} отклонён (401).`,
        '',
        'Скорее всего, пароль из SEED_PASSWORD_* больше не действует: при первом',
        'входе система требует его сменить, и с этого момента значение в .env',
        'устарело. Проверки нужно запускать с настоящими паролями:',
        '',
        '  sudo docker compose exec -T \\',
        '    -e SEED_PASSWORD_ADMIN=… -e SEED_PASSWORD_DIRECTOR=… \\',
        '    -e SEED_PASSWORD_ACCOUNTANT=… backend npm run check:audit',
        '',
        'Но подумайте дважды: проверки создают записи в БОЕВОЙ базе. Их место —',
        'тестовая копия (docs/qa/20_RELEASE_CHECKLIST.md).',
      ].join('\n'),
    );
  }
  if (status === 429) {
    throw new Error(
      `Вход под ${email} временно заблокирован (429): слишком много неудачных попыток. ` +
        'Подождите пять минут — это защита от перебора пароля.',
    );
  }
  throw new Error(`Вход под ${email} не удался: HTTP ${status} ${body.slice(0, 200)}`);
}
