/** Отметка «демо-данные вычищены».
 *
 *  deploy.sh запускает `npm run seed` при каждом деплое — это правильно,
 *  пока база демонстрационная: сид идемпотентен и добирает недостающее.
 *  Но после боевого запуска тот же сид вернул бы удалённое: заявки он
 *  восстанавливает явно (`deletedAt: null`), остатки счетов переписывает
 *  значениями из фикстур, а поставку по демо-сделке создал бы заново, не
 *  найдя живой.
 *
 *  Поэтому очистка оставляет в настройках отметку, а сид её проверяет и
 *  молча выходит с кодом 0 — деплой продолжается, демо-данные не всплывают.
 *
 *  Вернуть демо-данные (например, на тестовом стенде):
 *      npm run seed -- --force
 *  Отметка при этом снимается: база снова считается демонстрационной.
 */

export const DEMO_CLEANED_KEY = 'demo_cleaned_at';

export const DEMO_CLEANED_MESSAGE = (at: string) =>
  `\n[seed] Пропущен: демо-данные вычищены ${at}.\n`
  + '[seed] База считается боевой — сид вернул бы удалённые заявки,\n'
  + '[seed] остатки счетов и поставку по демо-сделке.\n'
  + '[seed] Если демо-данные всё же нужны: npm run seed -- --force\n';
